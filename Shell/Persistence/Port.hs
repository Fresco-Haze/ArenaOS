-- Shell.Persistence.Port
-- Repository ports (Architecture.md Section 13.4). These describe
-- what persistence must provide; they say nothing about how. No
-- adapter-specific imports belong here -- only Domain types and the
-- shared PersistenceError type.
--
-- Save/delete semantics: RC-01 (save is upsert), RC-02 (delete is
-- not idempotent -- deleting a missing object is NotFound).
-- Execution and failure model: ADR-007. Repository methods return
-- domain values directly; failures propagate as exceptions and are
-- translated to Either PersistenceError once, by the adapter runner
-- (e.g. runSQLiteM), not by these methods themselves.
-- NewTournament lives here rather than in Domain because it fails
-- the Two-Architectures Test: under a domain-generated-identity
-- backend (UUIDs), it wouldn't need to exist at all. It expresses a
-- persistence construction constraint, not a business concept.

module Shell.Persistence.Port
  ( ParticipantRepository(..)
  , TournamentRepository(..)
  , NewTournament(..)
  , RegistrationRepository(..)
  , Registration(..)
