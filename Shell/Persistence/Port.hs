-- Owns Participant identity (ADR-006) and its constituents (Player, Team).
-- resolveParticipant is the one operation every other repository depends
-- on indirectly -- it belongs here, per DP-002, not duplicated at each
-- call site.
class Monad m => ParticipantRepository m where
    savePlayer   :: Player -> m ()
    getPlayer    :: PlayerName -> m Player
    deletePlayer :: PlayerName -> m ()

    saveTeam     :: Team -> m ()
    getTeam      :: TeamName -> m Team
    deleteTeam   :: TeamName -> m ()
    teamExists   :: TeamName -> m Bool

    resolveParticipant :: Participant -> m ParticipantId
    getParticipant     :: ParticipantId -> m Participant

-- Creation-shaped input for TournamentRepository.createTournament.
-- Not a Domain Model type (see Document 3's own scope note) -- it
-- exists only because TournamentId is persistence-generated
-- (INTEGER PRIMARY KEY), so a pre-persistence Tournament value can
-- never honestly be constructed. Omits exactly the fields the
-- system determines, not the caller:
--   TournamentId    -- generated by persistence
--   TournamentState -- always Draft per FR-TM-001
--   TournamentBracket -- always Nothing at creation
-- Everything else (name, organizer, format, visibility, max
-- participants) is genuine caller input per FR-TM-001/002 -- see
-- the Tournament type itself, which has none of these as Maybe.
data NewTournament = NewTournament
    { newTournamentName            :: TournamentName
    , newTournamentOrganizer       :: OrganizerName
    , newTournamentFormat          :: TournamentFormat
    , newTournamentVisibility      :: Visibility
    , newTournamentMaxParticipants :: Int
    , newTournamentOwner :: UserId
    }

-- createTournament is NOT covered by RC-01 -- it has no natural key
-- to upsert against, so it is not idempotent: each call mints a
-- fresh TournamentId. saveTournament remains the RC-01-compliant
-- upsert path for all post-creation updates, including attaching a
-- Bracket once one is generated (tournament w/ NULL bracket_id ->
-- bracket -> saveTournament with tournamentBracket = Just newId,
-- per the schema's circular-FK insert order).
class Monad m => TournamentRepository m where
    createTournament :: NewTournament -> m TournamentId
    saveTournament   :: Tournament -> m ()
    getTournament    :: TournamentId -> m Tournament
    deleteTournament :: TournamentId -> m ()
    listTournamentsByOwner :: UserId -> m [Tournament]
    updateTournamentState    :: TournamentId -> TournamentState -> m ()
    updateTournamentName     :: TournamentId -> TournamentName -> m ()
    updateTournamentMaxParticipants :: TournamentId -> Int -> m ()
    updateTournamentVisibility :: TournamentId -> Visibility -> m ()
    updateTournamentFormat   :: TournamentId -> TournamentFormat -> m ()
    listAllTournaments :: m [Tournament]

-- Creation-shaped input for RegistrationRepository.createRegistration.
-- No status field -- RegistrationStatus has exactly one constructor
-- in v0.1 (INV-2, FR-TM-009); the repository hardcodes Confirmed at
-- insert, same pattern as createTournament hardcoding Draft.
-- Takes ParticipantId, not Participant -- identity resolution stays
-- exclusively in ParticipantRepository per DP-002; this repository
-- never calls resolveParticipant.
data NewRegistration = NewRegistration
    { newRegistrationTournament  :: TournamentId
    , newRegistrationParticipant :: ParticipantId
    }

-- No saveRegistration -- for v0.1, Registration has no legitimate
-- update surface: registrationTournament/registrationParticipant
-- are immutable once created (DI-10), and registrationStatus has
-- only one inhabitant. A future updateRegistrationStatus would be
-- the correct shape if INV-2 is ever exercised, not a blanket save.
class Monad m => RegistrationRepository m where
    createRegistration :: NewRegistration -> m RegistrationId
    getRegistration    :: RegistrationId -> m Registration
    deleteRegistration :: RegistrationId -> m ()
    listRegistrations  :: TournamentId -> m [Registration]


class Monad m => BracketRepository m where
    createBracket :: TournamentId -> m BracketId
    saveBracket :: Bracket -> [BracketNode] -> m (Map BracketNodeId BracketNodeId)
    getBracket    :: BracketId -> m (Bracket, [BracketNode])
    updateNodeSlots :: BracketNode -> m ()
    deleteBracket :: BracketId -> m ()

data NewMatch = NewMatch
    { newMatchTournament  :: TournamentId
    , newMatchBracket     :: BracketId
    , newMatchBracketNode :: BracketNodeId
    , newMatchCompetitorA :: ParticipantId
    , newMatchCompetitorB :: ParticipantId
    }
    deriving (Eq, Show)


class Monad m => MatchRepository m where
    createMatch           :: NewMatch -> m MatchId
    saveMatch             :: Match -> m ()
    getMatch              :: MatchId -> m Match
    listMatchesForBracket :: BracketId -> m [Match]
    deleteMatch           :: MatchId -> m ()

class Monad m => Transactional m where
    withTxN :: m a -> m a

data NewUser = NewUser
    { newUserUsername     :: Username
    , newUserEmail        :: Email
    , newUserPasswordHash :: PasswordHash
    }

